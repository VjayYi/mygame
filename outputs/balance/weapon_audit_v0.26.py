# 品类容积修正（沿用 v0.24）
VOL_FIX = {"刀":0,"剑":1,"爪":-1,"斧":-2,"拳套":-1,"步枪":0,"炮筒":-2,"手枪":1,"弓":1}
FORMS = {"改装": dict(vol=26, b=0), "均衡": dict(vol=18, b=1), "强攻": dict(vol=12, b=2)}

def card_v(c, b):
    name, cost, dmgs, shd, extra, *_ = c
    bb = -(-b // 2) if len(dmgs) >= 2 else b  # 多段卡：每段加成 = ceil(b/2)
    v = sum((d + bb) * E_DMG for d in dmgs)
    if name == "旋斧": v = (dmgs[0] + b) * 1.6 * E_DMG  # 全体
    if shd: v += (shd + b) * E_DMG
    return v + extra

def weapon_total(cat, form, b):
    sur = sum(card_v(c, b) - B(c[1]) for c in CARDS[cat])
    pas = PASSIVE[cat][2] if form == "均衡" else 0.0
    vol = FORMS[form]["vol"] + VOL_FIX[cat]
    return sur, pas, vol, sur + pas + KAPPA * vol

def run(b_bal=1, b_str=2):
    res = {}
    for cat in CARDS:
        row = {}
        for form, cfg in FORMS.items():
            b = {"改装":0,"均衡":b_bal,"强攻":b_str}[form]
            row[form] = weapon_total(cat, form, b)
        res[cat] = row
    return res

