def motif_for(name, mtype):
    if name in OVERRIDE:
        return OVERRIDE[name], "人工"
    for rule in RULES:
        for kw in rule[1:]:
            if kw in name:
                return rule[0], kw
    return TYPE_DEFAULT.get(mtype, "直"), "类型:" + mtype


def assign(name, mtype, old_size):
    """返回 (新格数, 形状 id, 母题, 依据)。新格数 = 旧格数 + 1；3 格一律直条。"""
    n = old_size + 1
    if n == 3:
        return n, "直3", "直", "3 格统一直条"
    motif, why = motif_for(name, mtype)
    return n, f"{motif}{n}", motif, why


def load_sources():
    audit = json.load(open(os.path.join(HERE, "module_audit_v0.26.json"), encoding="utf-8"))
    new = json.load(open(os.path.join(HERE, "new_cards_v028.json"), encoding="utf-8"))["mods"]
    rows = [(m["name"], m["type"], m["size"], "audit") for m in audit]
    rows += [(m["name"], m["type"], m["size"], "new") for m in new]
    return rows


def build_map():
    out = {}
    for name, mtype, size, src in load_sources():
        n, sid, motif, why = assign(name, mtype, size)
        out[name] = dict(size=n, shape=sid, motif=motif, why=why, type=mtype, old=size, src=src)
    return out


